"""Gate 8E: successor contract and acquisition-plan materialization (code only).

This module composes the existing provider-observed generators to produce, in one
atomic transaction, the four pieces of successor acquisition metadata:

    one data contract, one dataset version, one acquisition plan, 132 chunks

and nothing else. It creates no acquisition attempt, run, candle, manifest,
provider evidence, dataset registration or strategy output, and it contacts no
provider. Materialization against a persistent database is a separately
authorized gate; this module only makes the transition expressible.

Semantic note on ``discovery_version``
--------------------------------------
The contract payload retains ``discovery_version = "phase-2b1r-discovery-v1"``
for the successor, exactly as the predecessor contract carries it. That field
names the discovery *contract/schema generation*, which is unchanged, not the
particular discovery *plan generation*. The predecessor is the governing
precedent: its contract already carries ``phase-2b1r-discovery-v1`` while its
discovery plan is v2. Introducing ``phase-2b1r-discovery-v3`` here would invent a
contract identity with no governed precedent and conflate two distinct concepts.

The successor is instead distinguished and bound entirely through already
accepted evidence: its discovery plan SHA, request-manifest SHA, registration
report SHA, approval SHA, semantic inventory SHA, operational-evidence-set SHA,
restricted-overlap SHA and the accepted Gate 8D3 artifact digest, together with
the successor data identity and the deterministic identities derived from them.
Because the successor's semantic inventory and data identity differ, its contract
payload and every downstream identity necessarily differ from the predecessor's;
it can neither collide with nor masquerade as the predecessor.
"""

